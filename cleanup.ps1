$ErrorActionPreference = "SilentlyContinue"

Write-Host ""
Write-Host "============================================"
Write-Host "  BigFix Ops Studio | Cleanup Script"
Write-Host "============================================"
Write-Host ""

function Remove-IfExists($path) {
    if (Test-Path $path) {
        Write-Host "  Removing: $path"
        Remove-Item $path -Recurse -Force
    }
}

# ── Python build artifacts ────────────────────────────────────────
Write-Host "[1/4] Cleaning Python build artifacts..."

Remove-IfExists "build"
Remove-IfExists "dist"
Remove-IfExists "server.spec"

Get-ChildItem -Recurse -Include "__pycache__" -Directory | Remove-Item -Recurse -Force
Get-ChildItem -Recurse -Include "*.pyc"                  | Remove-Item -Force
Get-ChildItem -Recurse -Include "*.pyo"                  | Remove-Item -Force

Write-Host "  [OK] Python build artifacts removed."
Write-Host ""

# ── Encrypted data files and key ─────────────────────────────────
Write-Host "[2/4] Cleaning generated encryption files..."
Write-Host "  (These are regenerated by lock_data.py at the start of each build)"
Write-Host ""

# key.bin — the Fernet key generated by lock_data.py.
# It is bundled inside server.exe by PyInstaller and must never be
# committed to source control. Safe to delete here; build.ps1
# also auto-deletes it after bundling, but clean it here too in
# case a partial or interrupted build left it behind.
Remove-IfExists "key.bin"

# *.enc files — encrypted data files generated by lock_data.py.
# The originals (library.json, inspectors.json) are the source of truth.
# The .enc files are derived artifacts — delete and regenerate each build.
Remove-IfExists "library.enc"
Remove-IfExists "inspectors.enc"

Write-Host "  [OK] key.bin, library.enc, inspectors.enc removed."
Write-Host ""

# ── Electron build artifacts ──────────────────────────────────────
Write-Host "[3/4] Cleaning Electron artifacts..."

Remove-IfExists "electron\dist"
Remove-IfExists "electron\release"
Remove-IfExists "electron\out"
Remove-IfExists "electron\build"

Write-Host "  [OK] Electron build artifacts removed."
Write-Host ""

# ── Optional: Deep clean (node_modules + package-lock) ───────────
Write-Host "[4/4] Optional deep clean..."
Write-Host "  (Uncomment the lines below for a full reinstall of Electron dependencies)"
Write-Host ""

# Uncomment these two lines to also wipe node_modules and package-lock.json.
# Useful when switching Node/Electron versions or resolving dependency issues.
# After uncommenting, npm install will run automatically on the next build.ps1 run.
Remove-IfExists "electron\node_modules"
# Remove-IfExists "electron\package-lock.json"

Write-Host "  [OK] Deep clean skipped (node_modules preserved)."
Write-Host ""

# ── Summary ───────────────────────────────────────────────────────
Write-Host "============================================"
Write-Host "  Cleanup complete."
Write-Host "  Run build.ps1 for a fresh build."
Write-Host "  build.ps1 will auto-run lock_data.py to"
Write-Host "  regenerate key.bin and *.enc files."
Write-Host "============================================"
Write-Host ""

Read-Host "Press Enter to exit"