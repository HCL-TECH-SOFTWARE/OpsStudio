$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "============================================"
Write-Host "  BigFix Ops Studio | Build Script"
Write-Host "============================================"
Write-Host ""

Write-Host "[0/3] Encrypting data files (lock_data.py)..."
Write-Host ""

python lock_data.py
if ($LASTEXITCODE -ne 0) {
    Write-Host ""
    Write-Host "[ERROR] lock_data.py failed. Ensure library.json and inspectors.json exist." -ForegroundColor Red
    Read-Host "Press Enter to exit"
    exit 1
}

if (!(Test-Path "key.bin")) {
    Write-Host "[ERROR] key.bin was not generated by lock_data.py." -ForegroundColor Red
    Read-Host "Press Enter to exit"
    exit 1
}

Write-Host ""
Write-Host "[OK] key.bin, library.enc and inspectors.enc are ready."
Write-Host ""

Write-Host "[1/3] Freezing Python backend into server.exe..."
Write-Host ""

python -m PyInstaller `
    --name server `
    --onefile `
    --noconsole `
    --add-data="frontend:frontend" `
    --add-data="library.enc:." `
    --add-data="inspectors.enc:." `
    --add-data="key.bin:." `
    --collect-all chromadb `
    --collect-all tokenizers `
    --copy-metadata chromadb `
    --hidden-import google.genai `
    --hidden-import openai `
    --hidden-import anthropic `
    --hidden-import backend `
    --hidden-import backend.config `
    --hidden-import backend.server `
    --hidden-import backend.ai_handler `
    --hidden-import backend.qna_engine `
    --hidden-import cryptography `
    --hidden-import cryptography.fernet `
    --hidden-import cryptography.hazmat.primitives `
    --hidden-import cryptography.hazmat.primitives.asymmetric `
    --hidden-import cryptography.hazmat.primitives.asymmetric.rsa `
    --hidden-import cryptography.hazmat.primitives.hashes `
    --hidden-import cryptography.hazmat.primitives.serialization `
    --hidden-import cryptography.hazmat.backends `
    --hidden-import cryptography.x509 `
    --hidden-import cryptography.x509.oid `
    --hidden-import ssl `
    --hidden-import ipaddress `
    --hidden-import socket `
    --hidden-import datetime `
    --exclude-module PyQt5 `
    --exclude-module webview `
    --exclude-module pythonnet `
    --exclude-module clr `
    backend_entry.py

if ($LASTEXITCODE -ne 0) {
    Write-Host ""
    Write-Host "[ERROR] PyInstaller failed. Check errors above." -ForegroundColor Red
    Read-Host "Press Enter to exit"
    exit 1
}

Write-Host ""
Write-Host "[OK] server.exe created at dist\server.exe"
Write-Host ""

Write-Host "     Removing key.bin from source folder (already inside server.exe)..."
Remove-Item "key.bin" -Force -ErrorAction SilentlyContinue
Write-Host "     [OK] key.bin removed from source folder."
Write-Host ""

Write-Host "[2/3] Preparing Electron assets..."

Copy-Item "bigfix-logo.ico" "electron\bigfix-logo.ico" -Force -ErrorAction SilentlyContinue

if (!(Test-Path "electron\node_modules")) {
    Write-Host "Installing Electron dependencies (first time only)..."

    Push-Location "electron"

    npm install
    if ($LASTEXITCODE -ne 0) {
        Write-Host ""
        Write-Host "[ERROR] npm install failed" -ForegroundColor Red
        Pop-Location
        Read-Host "Press Enter to exit"
        exit 1
    }

    Pop-Location
}

Write-Host "[OK] Electron ready."
Write-Host ""

Write-Host "[3/3] Building Windows installer..."
Write-Host ""

Push-Location "electron"

npm run build
if ($LASTEXITCODE -ne 0) {
    Write-Host ""
    Write-Host "[ERROR] Electron build failed. Check errors above." -ForegroundColor Red
    Pop-Location
    Read-Host "Press Enter to exit"
    exit 1
}

Pop-Location

Write-Host ""
Write-Host "============================================"
Write-Host "  Build Complete!"
Write-Host "  Installer: electron\release\BigFix Ops Studio Setup.exe"
Write-Host "============================================"
Write-Host ""

Read-Host "Press Enter to exit"
